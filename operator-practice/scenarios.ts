export function getSectorOption(sector: PracticeSector): SectorOption {
  const option = SECTORS.find((candidate) => candidate.id === sector);

  if (!option) {
    throw new Error(`Unknown practice sector: ${sector}`);
  }

  return option;
}

export function getScenariosForSector(
  sector: PracticeSector,
): readonly PracticeScenario[] {
  return PRACTICE_SCENARIOS.filter((scenario) => scenario.sector === sector);
}

export function getScenarioById(id: string): PracticeScenario | undefined {
  return PRACTICE_SCENARIOS.find((scenario) => scenario.id === id);
}
